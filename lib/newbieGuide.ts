// Ответы с клиента: ровно по одному верному на каждый урок, по порядку
export function checkGuideAnswers(answers: unknown): boolean {
  return (
    Array.isArray(answers) &&
    answers.length === GUIDE_LESSONS.length &&
    answers.every((a, i) => a === GUIDE_LESSONS[i].question.correct)
  );
}

// Прогресс в localStorage — верные ответы по порядку. Берём только верное начало: испорченная
// или чужая запись не пропустит человека дальше, чем он прошёл.
export function restoreGuideProgress(raw: string | null): number[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw ?? '');
  } catch {
    return [];
  }
  if (!Array.isArray(parsed)) return [];
  const done: number[] = [];
  for (const [i, lesson] of GUIDE_LESSONS.entries()) {
    if (parsed[i] !== lesson.question.correct) break;
    done.push(parsed[i]);
  }
  return done;
}

export function guideStorageKey(userId: string): string {
  return `spor3s_guide_v1:${userId}`;
}
